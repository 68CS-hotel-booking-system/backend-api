CREATE TYPE user_status__t AS ENUM (
    'active',
    'inactive',
    'pending',
    'banned'
);

CREATE TABLE users (
                     id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                     email VARCHAR(255) NOT NULL,
                     password_hash VARCHAR(255) NOT NULL,
                     full_name VARCHAR(100) NOT NULL,
                     phone VARCHAR(20) NOT NULL,
                     avatar_url VARCHAR(255),
                     status user_status__t NOT NULL DEFAULT 'pending',
                     email_verified_at TIMESTAMPTZ,
                     is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                     version BIGINT NOT NULL DEFAULT 0,

                     CONSTRAINT uq_users_email UNIQUE (email),
                     CONSTRAINT uq_users_phone UNIQUE (phone),
                     CONSTRAINT ck_users_email_normalized
                       CHECK (email = lower(btrim(email)))
);

CREATE TABLE roles (
                     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     role_key VARCHAR(50) NOT NULL UNIQUE,
                     role_name VARCHAR(150) NOT NULL,
                     description VARCHAR(255),
                     is_active BOOLEAN NOT NULL DEFAULT TRUE,
                     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                     updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_roles (
                          id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                          user_id UUID NOT NULL REFERENCES users(id),
                          role_id INTEGER NOT NULL REFERENCES roles(id),
                          assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),

                          CONSTRAINT uq_user_roles_user_role UNIQUE (user_id, role_id)
);

CREATE INDEX idx_user_roles_role_id
  ON user_roles(role_id);

CREATE TABLE email_verification_tokens (
                                         id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                                         user_id UUID NOT NULL REFERENCES users(id),
                                         token_hash VARCHAR(64) NOT NULL,
                                         expires_at TIMESTAMPTZ NOT NULL,
                                         used_at TIMESTAMPTZ,
                                         revoked_at TIMESTAMPTZ,
                                         created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

                                         CONSTRAINT uq_email_verification_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_email_verification_tokens_user
  ON email_verification_tokens(user_id);

CREATE INDEX idx_email_verification_tokens_expiry
  ON email_verification_tokens(expires_at);

